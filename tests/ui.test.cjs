/* Run against npm run preview. Requires Playwright in the runtime, not in the app. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_BUNDLED ? undefined : (process.env.CHROMIUM_PATH||'/usr/bin/chromium'),headless:true,args:['--no-sandbox']});
  try {
    const context=await browser.newContext({viewport:{width:412,height:915},deviceScaleFactor:1});
    const page=await context.newPage();const errors=[];page.on('pageerror',err=>errors.push(err.message));
    await page.goto('http://127.0.0.1:4173');
    await page.getByRole('button',{name:'New case',exact:false}).click();
    await page.locator('#case-title').fill('Training — suspicious sign-in review');
    await page.locator('#case-priority').selectOption('High');
    await page.locator('#case-category').selectOption('Account compromise');
    await page.locator('#case-observation').fill('Training record. A sign-in from documentation IP 192.0.2.44 was reported. Account access and exposure remain unverified.');
    await page.getByRole('button',{name:'Create case'}).click();
    await page.locator('#note-text').fill('Compared the event time with the user report. Preserve the original authentication log before drawing conclusions.');
    await page.getByRole('button',{name:'Save observation',exact:true}).click();
    const caseUrl=page.url();await page.reload();
    await page.getByText('Compared the event time',{exact:false}).waitFor();
    await page.getByRole('link',{name:'Account compromise 0 / 6 steps recorded'}).click();
    await page.getByRole('checkbox').first().check();
    await page.reload();assert.equal(await page.getByRole('checkbox').first().isChecked(),true);
    await page.getByRole('link',{name:'Overview',exact:false}).first().click();
    fs.mkdirSync('docs/screenshots',{recursive:true});
    await page.screenshot({path:'docs/screenshots/phone-overview.png',fullPage:true});
    await page.goto(caseUrl);
    await page.screenshot({path:'docs/screenshots/phone-case.png',fullPage:true});
    await page.goto('http://127.0.0.1:4173/#tools/hash');
    await page.locator('#hash-text').fill('abc');await page.getByRole('button',{name:'Hash text',exact:true}).click();
    const expected='ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad';
    assert.equal(await page.locator('#hash-result code').textContent(),expected);
    await page.locator('#expected-hash').fill(expected);assert.match(await page.locator('#hash-comparison').textContent(),/^Match/);
    await page.locator('#expected-hash').fill('0'.repeat(64));assert.match(await page.locator('#hash-comparison').textContent(),/^No match/);
    await page.locator('#file-input').setInputFiles({name:'known.txt',mimeType:'text/plain',buffer:Buffer.from('abc')});
    await page.waitForFunction(()=>document.querySelector('#hash-result small')?.textContent.includes('known.txt'));
    assert.equal(await page.locator('#hash-result code').textContent(),expected);
    await page.goto('http://127.0.0.1:4173/#tools/ioc');
    await page.locator('#ioc-text').fill('hxxps://portal[.]example[.]org 192.0.2.44 <img src=x onerror="alert(1)">');
    await page.getByRole('button',{name:'Extract indicators',exact:true}).click();
    assert.ok(await page.locator('.indicator').count()>=3);
    assert.equal(await page.locator('#main img').count(),0);
    await page.getByRole('button',{name:'Save findings as an observation'}).click();
    await page.goto(caseUrl);await page.getByText('Extracted patterns — UNVERIFIED',{exact:false}).waitFor();
    const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Export report'}).click();
    const download=await downloadEvent;const path=await download.path();assert.match(fs.readFileSync(path,'utf8'),/Extracted patterns — UNVERIFIED/);
    const raw=await page.evaluate(()=>localStorage.getItem('centinellia.workspace.v1'));
    await page.goto('http://127.0.0.1:4173/#settings');
    await page.locator('#backup-input').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(raw)});
    await page.getByText('0 cases imported. 1 existing IDs skipped.',{exact:true}).waitFor();
    const before=await page.evaluate(()=>localStorage.getItem('centinellia.workspace.v1'));
    await page.locator('#backup-input').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{broken')});
    await page.getByText('This is not a valid JSON backup.',{exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>localStorage.getItem('centinellia.workspace.v1')),before);
    await page.getByRole('button',{name:'Delete all local cases'}).click();await page.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(await page.evaluate(()=>localStorage.getItem('centinellia.workspace.v1')),before);
    await page.getByRole('button',{name:'Delete all local cases'}).click();await page.getByRole('button',{name:'Confirm',exact:true}).click();
    assert.equal(await page.evaluate(()=>localStorage.getItem('centinellia.workspace.v1')),null);
    // Storage failure must not display unsaved cases as successfully created.
    await page.evaluate(()=>Object.defineProperty(Storage.prototype,'setItem',{value(){throw new DOMException('Storage full','QuotaExceededError');},configurable:true}));
    await page.goto('http://127.0.0.1:4173/#cases');
    await page.getByRole('button',{name:'New case',exact:false}).click();await page.locator('#case-title').fill('Unsaved');await page.getByRole('button',{name:'Create case'}).click();
    assert.equal(await page.locator('#case-dialog').evaluate(d=>d.open),true);
    await page.getByRole('button',{name:'Close',exact:true}).click();
    assert.equal(await page.locator('.case-row').count(),0);
    await page.reload();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.setViewportSize({width:1440,height:1000});await page.goto('http://127.0.0.1:4173/#overview');
    await page.screenshot({path:'docs/screenshots/desktop-overview.png',fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.deepEqual(errors,[]);console.log('UI PASS: persistence, checklists, hashing, extraction, export, import, deletion, storage failure, mobile/desktop layout.');
    await browser.close();
  } catch(err) {await browser.close();throw err;}
})();
